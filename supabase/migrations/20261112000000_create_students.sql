-- SimpleStudent – first migration: table "Students"
--
-- Applied automatically by GitHub Actions (supabase db push):
--   push to release/vX.Y.Z           → Supabase project "SimpleStudent System Test"
--   tag vX.Y.Z on main               → Supabase project "SimpleStudentSystem" (Production)
-- Every migration runs only ONCE per database; Supabase remembers it in
-- supabase_migrations.schema_migrations. A NEW change = a NEW file:
--   supabase migration new add_phone_to_students
--
-- Same table as database/postgres/create.sql (local Docker). Names in double quotes keep their
-- capital letters ("Students", "FirstName") – exactly the names the .NET API (EF Core) uses,
-- so the Node.js API and later any other API can share this table.
-- IF NOT EXISTS: safe for a project where create.sql was already run by hand in the SQL Editor.

CREATE TABLE IF NOT EXISTS "Students" (
    "Id"             integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "FirstName"      varchar(100) NOT NULL,
    "LastName"       varchar(100) NOT NULL,
    "Email"          varchar(200) NOT NULL,
    "StudyProgram"   varchar(100) NOT NULL,
    "EnrollmentYear" integer      NOT NULL
);

-- Supabase publishes every table of the "public" schema through its own REST API (anon key).
-- Row Level Security without any policy closes that door; our APIs connect as the table owner
-- (user postgres), which RLS does not restrict.
ALTER TABLE "Students" ENABLE ROW LEVEL SECURITY;
